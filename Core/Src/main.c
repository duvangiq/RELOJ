// Busca la MPU6050 en el bus I2C (0x68 o 0x69). Devuelve la dirección de 7 bits o 0.
static uint8_t MPU6050_Buscar(void)
{
  if (HAL_I2C_IsDeviceReady(&hi2c1, 0x68 << 1, 3, 50) == HAL_OK) return 0x68;
  if (HAL_I2C_IsDeviceReady(&hi2c1, 0x69 << 1, 3, 50) == HAL_OK) return 0x69;
  return 0;
}

